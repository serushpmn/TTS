const LOCALES: Record<UiLocale, Dict> = { en, fa, de };

export const UI_LOCALES: { id: UiLocale; label: string }[] = [
  { id: "en", label: "EN" },
  { id: "fa", label: "FA" },
  { id: "de", label: "DE" },
];

export function t(locale: UiLocale, key: string): string {
  return LOCALES[locale][key] ?? LOCALES.en[key] ?? key;
}

/** Replace `{name}` style placeholders in a translated string. */
export function tf(locale: UiLocale, key: string, vars: Record<string, string | number>): string {
  let out = t(locale, key);
  for (const [name, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
}

export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string;

export function isRtl(locale: UiLocale): boolean {
  return locale === "fa";
}
