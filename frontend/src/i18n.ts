const LOCALES: Record<UiLocale, Dict> = { en, fa, de };

export const UI_LOCALES: { id: UiLocale; label: string }[] = [
  { id: "en", label: "EN" },
  { id: "fa", label: "FA" },
  { id: "de", label: "DE" },
];

export function t(locale: UiLocale, key: string): string {
  return LOCALES[locale][key] ?? LOCALES.en[key] ?? key;
}

export function isRtl(locale: UiLocale): boolean {
  return locale === "fa";
}
